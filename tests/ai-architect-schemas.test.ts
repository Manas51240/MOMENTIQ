import { describe, it, expect } from 'vitest';
import {
  eventArchitectInputSchema,
  eventArchitectPlanSchema,
  executiveConceptSchema,
  recommendedThemeSchema,
  budgetAllocationSchema,
  planningMilestonesSchema,
  vendorChecklistSchema,
  guestManagementPlanSchema,
  eventDayScheduleSchema,
  menuSuggestionsSchema,
  entertainmentPlanSchema,
  contingencyPlanSchema,
  importantAssumptionsSchema,
} from '../src/lib/ai/schemas';
import { generateDeterministicPlan } from '../src/lib/ai/deterministic-fallback';

describe('AI Event Architect Schema & Structural Validation Suite', () => {
  const sampleValidInput = {
    category: 'WEDDING' as const,
    eventDate: new Date(Date.now() + 86400000 * 90).toISOString(),
    durationHours: 6,
    location: 'Monterey Peninsula, California',
    budgetMinor: 4000000, // $40,000.00
    currency: 'USD',
    guestCount: 120,
    eventStyle: 'Coastal Elegance',
    theme: 'Pacific Sunset Romance',
    culturalPreferences: ['Bilingual toasts in English and Spanish'],
    dietaryPreferences: ['Gluten-Free', 'Vegetarian'],
    venuePreferences: 'Ocean-view pavilion with terrace',
    indoorOutdoor: 'HYBRID' as const,
    accessibilityRequirements: ['Wheelchair ramp to beach pavilion'],
    specialInstructions: 'Incorporate acoustic Spanish guitar during ceremony',
  };

  it('validates 14 complete input parameters', () => {
    const parsed = eventArchitectInputSchema.parse(sampleValidInput);
    expect(parsed.category).toBe('WEDDING');
    expect(parsed.budgetMinor).toBe(4000000);
    expect(parsed.durationHours).toBe(6);
    expect(parsed.indoorOutdoor).toBe('HYBRID');
  });

  it('rejects input with invalid category or negative budget', () => {
    // Invalid category
    expect(() =>
      eventArchitectInputSchema.parse({
        ...sampleValidInput,
        category: 'INVALID_CATEGORY',
      })
    ).toThrow();

    // Budget below minimum 10,000 minor units
    expect(() =>
      eventArchitectInputSchema.parse({
        ...sampleValidInput,
        budgetMinor: -500,
      })
    ).toThrow();
  });

  it('validates complete 12-section master plan generated by the deterministic engine', () => {
    const plan = generateDeterministicPlan(sampleValidInput);
    const validated = eventArchitectPlanSchema.parse(plan);

    expect(validated.isAiGenerated).toBe(true);
    expect(validated.verified).toBe(false);
    expect(validated.executiveConcept.title).toBeDefined();
    expect(validated.recommendedTheme.colorPalette.primary).toMatch(/^#[A-Fa-f0-9]{6}$/);
    expect(validated.budgetAllocation.categories.length).toBeGreaterThanOrEqual(3);
    expect(validated.planningMilestones.milestones.length).toBeGreaterThanOrEqual(3);
    expect(validated.vendorChecklist.vendors.length).toBeGreaterThanOrEqual(3);
    expect(validated.guestManagementPlan.accessibilityAccommodations.length).toBeGreaterThanOrEqual(1);
    expect(validated.eventDaySchedule.timeline.length).toBeGreaterThanOrEqual(4);
    expect(validated.menuSuggestions.dietaryOptions.length).toBeGreaterThanOrEqual(1);
    expect(validated.entertainmentPlan.mainAttractions.length).toBeGreaterThanOrEqual(1);
    expect(validated.contingencyPlan.scenarios.length).toBeGreaterThanOrEqual(2);
    expect(validated.importantAssumptions.disclaimers.length).toBeGreaterThanOrEqual(2);
  });

  it('enforces integer currency minor units in budget allocations', () => {
    const invalidBudget = {
      totalBudgetMinor: 5000.5, // Float is illegal
      currency: 'USD',
      categories: [
        { name: 'Venue', percentage: 50, allocatedMinor: 2500.25, rationale: 'Test' },
      ],
      contingencyMinor: 500,
      contingencyPercentage: 10,
    };

    expect(() => budgetAllocationSchema.parse(invalidBudget)).toThrow();
  });

  it('rejects theme with malformed hex color codes', () => {
    const invalidTheme = {
      name: 'Bad Theme',
      description: 'A theme with invalid colors for testing',
      colorPalette: {
        primary: 'blue-not-hex',
        secondary: '#123456',
        accent: '#abcdef',
        neutral: '#ffffff',
      },
      aestheticMotifs: ['Motif 1', 'Motif 2'],
      dressCode: 'Formal',
    };

    expect(() => recommendedThemeSchema.parse(invalidTheme)).toThrow(/Invalid primary color hex/);
  });

  it('rejects plan missing mandatory sections', () => {
    const incompletePlan = {
      version: 'v1.2.0',
      generatedAt: new Date().toISOString(),
      isAiGenerated: true,
      verified: false,
      executiveConcept: {
        title: 'Title',
        tagline: 'Tagline text',
        overview: 'Overview of the celebration in detail here.',
        keyHighlights: ['Highlight 1', 'Highlight 2'],
        atmosphere: 'Celebratory ambiance',
      },
      // Missing all other 11 sections
    };

    expect(() => eventArchitectPlanSchema.parse(incompletePlan)).toThrow();
  });
});

